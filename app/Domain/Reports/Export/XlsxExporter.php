<?php

namespace App\Domain\Reports\Export;

use App\Domain\Reports\ReportResult;
use OpenSpout\Common\Entity\Row;
use OpenSpout\Common\Entity\Style\Style;
use OpenSpout\Writer\XLSX\Entity\SheetView;
use OpenSpout\Writer\XLSX\Options;
use OpenSpout\Writer\XLSX\Writer;

/** Excel export (docs/09 §4): report sheet with frozen header and totals row, plus a sheet describing the filters. Money in rupees. */
class XlsxExporter
{
    public function write(ReportResult $r, string $path): void
    {
        $bold = (new Style)->setFontBold();
        $options = new Options;
        $writer = new Writer($options);
        $writer->openToFile($path);

        $sheet = $writer->getCurrentSheet();
        $sheet->setName(mb_substr(preg_replace('/[\\\\\/\?\*\[\]:]/', '', $r->code), 0, 31));

        $writer->addRow(Row::fromValues(array_map(fn ($c) => $c->label.($c->type === 'money' ? ' (₹)' : ''), $r->columns), $bold));
        foreach ($r->rows as $row) {
            $writer->addRow(Row::fromValues(array_map(fn ($c) => $c->excelValue($row[$c->key] ?? null), $r->columns)));
        }
        if ($r->totals) {
            $writer->addRow(Row::fromValues(array_map(fn ($c) => $c->excelValue($r->totals[$c->key] ?? null), $r->columns), $bold));
        }
        $sheet->setSheetView((new SheetView)->setFreezeRow(2));

        $about = $writer->addNewSheetAndMakeItCurrent();
        $about->setName(__('About'));
        foreach ([
            [$r->heading ?? $r->title],
            [__('Report'), "{$r->code} · {$r->title}"],
            [__('Data as of'), $r->asOf->format('d-m-Y H:i')],
            [__('Generated by'), $r->generatedBy],
            ...array_map(fn ($line) => [__('Filter'), $line], $r->filterSummary),
            [__('Note'), __('Figures are from approved progress updates only. Money in rupees.')],
        ] as $line) {
            $writer->addRow(Row::fromValues($line));
        }
        foreach ($r->summary as $label => $value) {
            $writer->addRow(Row::fromValues([$label, $value]));
        }
        if ($r->note) {
            $writer->addRow(Row::fromValues([__('Cover note'), $r->note]));
        }

        $writer->close();
    }
}
